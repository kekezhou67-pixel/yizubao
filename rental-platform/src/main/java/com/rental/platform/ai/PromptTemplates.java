package com.rental.platform.ai;

/**
 * RAG Prompt 模板集中管理（AI 改造 · 阶段5）
 *
 * 讲义02 最佳实践：Prompt 模板与业务代码分离，JDK15+ 三引号文本块。
 * 讲义04 核心结论：RAG 答案质量 = 检索质量 + Prompt 约束，缺一不可。
 * 防幻觉靠"资料中没有就如实说不知道"的硬约束。
 */
public final class PromptTemplates {

    private PromptTemplates() {}

    /**
     * 政策问答（带引用）
     * {context} 由 RagService 拼装：编号 + 父块内容 + 文档标题
     */
    public static final String RAG_QA = """
            <角色>你是易租宝租房平台的政策与法律助手。</角色>
            <任务>只依据<资料>回答用户问题，并在引用处标注资料编号。</任务>
            <约束>
            1. 不得引入<资料>之外的法律知识，禁止编造法条
            2. 引用资料时使用【资料N】标注（N 是资料编号）
            3. 资料中没有相关信息时，明确回答"资料中没有相关信息"，并建议用户咨询当地住建部门或专业律师
            4. 回答简洁、口语化，先给结论再给依据
            </约束>
            <资料>
            {context}
            </资料>
            <问题>{question}</问题>
            """;

    /**
     * 合同条款审查（阶段6 用）：带检索到的法条判断单个条款风险
     */
    public static final String CONTRACT_CLAUSE_REVIEW = """
            <角色>你是租房合同审查律师。</角色>
            <任务>依据<法条资料>审查<合同条款>是否存在风险。</任务>
            <约束>
            1. 只能引用<法条资料>中出现的法条作为依据，禁止编造法条编号
            2. 法条资料中没有相关规定时，law 字段填"未检索到直接相关法条"，基于公平原则分析
            3. risk 为 true 表示该条款对承租人明显不利或违法
            </约束>
            <法条资料>
            {laws}
            </法条资料>
            <合同条款>
            {clause}
            </合同条款>
            """;
}
